"""AI-generated DRAFT prescription, built from the latest checkup results.

A rule-based "AI doctor": it turns each result into the tests, the specific
medicines a doctor would typically consider (with common brand names you can
ask for at a medical shop), and the follow-up. It is NOT a real prescription:
  * it never gives doses - dose, timing and duration are for a real doctor;
  * most listed medicines are prescription-only, so a pharmacy will ask for a
    doctor's prescription;
  * medicines are only shown for adults (18+);
  * every output carries the disclaimer below.
"""

DISCLAIMER = (
    "This prescription was generated by an AI system from statistical estimates. It was NOT written by a "
    "doctor and it is not a diagnosis. Please consult a doctor before taking any medicine, and do not trust "
    "it blindly. Medicines marked Rx are prescription-only: never start, stop or change one without a doctor."
)
DOSE_NOTE = "Dose, timing and duration: to be decided by your doctor."
RX_NOTE = "Prescription-only: the medical shop will ask for a doctor's prescription."
ALWAYS_TELL = ("Tell your doctor about your allergies, pregnancy, kidney or liver disease, and every medicine "
               "or supplement you already take.")
BRAND_NOTE = ("Brand names are common examples only and differ by country and company. Ask the pharmacist for the "
              "equivalent and buy only from a licensed medical shop.")


def _item(kind, title, detail, rx=False):
    return {"kind": kind, "title": title, "detail": detail, "rx": rx}


def _medicine(generic, brands, purpose):
    """A named medicine: generic name as title, brands + what it is for + Rx and dose notes as detail."""
    return _item("medicine", generic, f"Common brands: {brands}. {purpose} {RX_NOTE} {DOSE_NOTE}", rx=True)


def _bp_stage(detail):
    d = (detail or "").lower()
    if "crisis" in d:
        return "crisis"
    if "stage 2" in d:
        return "stage2"
    if "stage 1" in d:
        return "stage1"
    if "elevated" in d:
        return "elevated"
    return None


def build_prescription(latest, age=None):
    """latest = {checkup_type: {"flag": int, "detail": str, "inputs": dict}} -> prescription dict."""
    adult = age is None or int(age) >= 18
    items, conditions = [], []
    seen = set()

    def add(item):
        key = (item["kind"], item["title"])
        if key not in seen:
            seen.add(key)
            items.append(item)

    heart = latest.get("heart")
    diabetes = latest.get("diabetes")
    sugar = latest.get("sugar")
    bp = latest.get("bp")

    # ---------------------------------------------------------------- heart
    if heart and heart.get("flag") == 2:
        conditions.append("High estimated risk of heart disease")
        add(_item("test", "Heart tests", "ECG, echocardiogram, lipid profile (cholesterol) and a stress (treadmill) "
                  "test, as advised by a cardiologist."))
        if adult:
            add(_medicine("Aspirin (low-dose)", "Ecosprin, Loprin",
                          "A blood thinner (antiplatelet) often advised to lower heart-attack risk. It can cause bleeding."))
            add(_medicine("Atorvastatin", "Atorva, Storvas, Lipitor",
                          "A statin that lowers cholesterol. Needs a liver check."))
            if (heart.get("inputs") or {}).get("resting_blood_pressure", 0) >= 130:
                add(_medicine("Metoprolol", "Betaloc, Metolar",
                              "A beta-blocker that lowers heart rate and blood pressure. Not suitable for people with asthma."))
        add(_item("followup", "See a cardiologist", "Within 1 to 2 weeks."))
        add(_item("urgent", "Emergency warning signs",
                  "Go to an emergency room now for chest pain or pressure, pain spreading to the arm or jaw, "
                  "breathlessness, cold sweat or fainting."))

    # ------------------------------------------------------------- diabetes
    diabetic = (diabetes and diabetes.get("flag") == 2) or (sugar and sugar.get("flag") == 2)
    if diabetic:
        conditions.append("High estimated risk of diabetes / sugar in the diabetic range")
        add(_item("test", "Diabetes tests", "Fasting glucose, post-meal glucose and HbA1c, plus kidney function "
                  "(creatinine), urine albumin and a lipid profile."))
        if adult:
            add(_medicine("Metformin", "Glycomet, Glucophage",
                          "The usual first-line tablet for type 2 diabetes. Needs a kidney-function check first, and "
                          "a doctor must confirm the diagnosis before it is started."))
        add(_item("followup", "See a doctor or diabetologist",
                  "Within 1 to 2 weeks. A single estimate or reading is not a diagnosis."))
        add(_item("urgent", "Emergency warning signs",
                  "Get urgent care for very high sugar with vomiting, confusion, fast breathing or fruity-smelling breath."))
    elif sugar and sugar.get("flag") == 1:
        conditions.append("Sugar in the prediabetic range")
        add(_item("test", "Repeat sugar tests", "Fasting glucose and HbA1c again in about 3 months."))
        add(_item("medicine", "No medicine usually needed at this stage",
                  "Doctors normally start with monitoring; they may discuss metformin only in higher-risk cases.", rx=False))
        add(_item("followup", "Recheck", "In about 3 months, or sooner if you develop thirst, frequent urination or fatigue."))

    # ------------------------------------------------------- blood pressure
    stage = _bp_stage(bp.get("detail")) if bp else None
    if stage:
        names = {"elevated": "Elevated blood pressure", "stage1": "Hypertension stage 1",
                 "stage2": "Hypertension stage 2", "crisis": "Hypertensive crisis"}
        conditions.append(names[stage])
    if stage == "crisis":
        add(_item("urgent", "Seek emergency medical care today",
                  "A reading in the crisis range needs urgent medical attention, especially with headache, chest "
                  "pain, breathlessness, vision changes or weakness."))
    elif stage == "elevated":
        add(_item("test", "Home blood-pressure log", "Measure morning and evening for 1 to 2 weeks and bring the readings."))
        add(_item("medicine", "No blood-pressure medicine usually needed at this stage",
                  "Doctors normally monitor first.", rx=False))
        add(_item("followup", "Recheck", "In about 1 month."))
    elif stage in ("stage1", "stage2"):
        add(_item("test", "Blood-pressure work-up", "Kidney function, electrolytes, lipid profile and an ECG."))
        if adult:
            if stage == "stage1":
                add(_medicine("Amlodipine", "Amlong, Amlokind, Norvasc",
                              "A calcium-channel blocker for high blood pressure. Your doctor picks ONE option from this list."))
                add(_medicine("Telmisartan", "Telma, Micardis",
                              "An ARB-type blood-pressure medicine. Not for use in pregnancy. Your doctor picks ONE option from this list."))
            else:
                add(_medicine("Telmisartan + Amlodipine (combined tablet)", "Telma-AM",
                              "At stage 2 doctors often combine two medicines in one tablet."))
                add(_medicine("Telmisartan + Hydrochlorothiazide (combined tablet)", "Telma-H",
                              "A combination with a water tablet (diuretic); another common choice for stage 2."))
        add(_item("followup", "See a doctor", "Within 1 week." if stage == "stage2" else "Within 2 to 4 weeks."))
    if stage in ("elevated", "stage1", "stage2", "crisis"):
        add(_item("caution", "Pain-killers that can raise blood pressure",
                  "Avoid ibuprofen (Brufen) and diclofenac (Voveran) and cold/decongestant tablets unless a doctor says they are safe."))

    needs = any(i["kind"] in ("medicine", "test", "followup", "urgent") for i in items)
    if not adult and any(i["kind"] == "test" for i in items):
        add(_item("caution", "Medicines are not suggested for under-18s", "Please see a paediatrician for treatment."))
    if needs:
        add(_item("caution", "Before any medicine", ALWAYS_TELL))
    if any(i["kind"] == "medicine" and i["rx"] for i in items):
        add(_item("caution", "About the brand names", BRAND_NOTE))
    return {
        "needs_attention": needs,
        "conditions": conditions,
        "items": items,
        "summary": ("Based on your latest results, these are the tests, medicines and follow-up a doctor would "
                    "typically discuss with you." if needs else
                    "No prescription is suggested: your latest results are in a normal range. "
                    "Repeat the checkups from time to time."),
        "disclaimer": DISCLAIMER,
    }
